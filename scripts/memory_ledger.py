Message = Tuple[str, str]  # (stream, text) where stream is "out" or "err"


class LedgerError(Exception):
    """Raised for usage errors such as a missing memory directory."""


def glob_in(directory: str, *tail: str) -> List[str]:
    """Glob below a directory whose name may itself contain glob characters."""
    return glob.glob(os.path.join(glob.escape(directory), *tail), recursive=True)


def read_text(path: str) -> str:
    """Read a file as UTF-8, replacing undecodable bytes; unreadable files read as empty.

    One bad file must never abort a whole check or hide findings in other files.
    """
    try:
        with open(path, encoding="utf-8", errors="replace") as handle:
            return handle.read()
    except OSError:
        return ""


def list_header_kind(value: str) -> Optional[str]:
    """Classify the value part of a LIST_KEYS line.

    Returns:
        "open" for an empty value (items follow), "empty" for `[]`, and None
        for any other scalar. A trailing `# comment` is ignored.
    """
    bare = COMMENT_RE.sub("", value).strip()
    if not bare:
        return "open"
    if EMPTY_FLOW_LIST_RE.match(bare):
        return "empty"
    return None


def format_overdue(strings: Dict[str, str], days: int) -> str:
    """Render the overdue suffix with a correctly pluralised unit."""
    return strings["overdue"].format(days=days, unit="day" if days == 1 else "days")


def unquote(value: str) -> str:
    """Strip one matching pair of surrounding YAML quotes.

    Double-quoted values unescape `\\"` and `\\\\` (other escapes stay literal);
    single-quoted values unescape `''`. Unbalanced quotes, or a closing quote
    that is itself escaped, leave the value untouched.
    """
    if len(value) < 2 or value[0] != value[-1] or value[0] not in "\"'":
        return value
    inner = value[1:-1]
    if value[0] == "'":
        return inner.replace("''", "'")
    trailing = len(inner) - len(inner.rstrip("\\"))
    if trailing % 2:  # the closing quote was escaped, so the string is unterminated
        return value
    return DOUBLE_ESCAPE_RE.sub(r"\1", inner)


def parse_frontmatter(path: str) -> Optional[Dict[str, object]]:
    """Parse the leading `---` block of a markdown file.

    Args:
        path: File to read.

    Returns:
        Flat dict of keys to strings; LIST_KEYS are always lists (a scalar
        value on such a key is ignored). None when there is no frontmatter.
    """
    lines = read_text(path).split("\n")
    if not lines or lines[0].strip() != "---":
        return None
    fm: Dict[str, object] = {}
    list_key: Optional[str] = None
    for line in lines[1:]:
        if line.strip() == "---":
            break

        # List items bind to the most recent LIST_KEYS header. Checked before
        # KV_RE because "- date: x" would otherwise match neither and be lost.
        item = LIST_ITEM_RE.match(line)
        if list_key and item and item.group(1).strip():
            text = unquote(item.group(1).strip())
            if text:
                fm[list_key].append(text)  # type: ignore[union-attr]
            continue

        match = KV_RE.match(line)
        if not match:
            continue
        key, value = match.group(1), match.group(2).strip()
        if key in LIST_KEYS:
            kind = list_header_kind(value)
            if kind is not None:
                fm.setdefault(key, [])
                list_key = key if kind == "open" else None
            else:
                list_key = None  # a scalar on a list key is not a list: ignore it
            continue
        # Any other key ends the list block, so a stray item cannot attach to a
        # header several fields above it.
        list_key = None
        value = unquote(value)
        if value:
            fm[key] = value
    return fm


class Validator:
    """Static checks over one memory directory."""

    def __init__(self, memory_dir: str, strings: Dict[str, str]) -> None:
        """Bind the validator to a directory and a locale table."""
        self.memory_dir = memory_dir
        self.strings = strings
        self.index_path = os.path.join(memory_dir, "MEMORY.md")
        self.archive_index_path = os.path.join(memory_dir, "archive_index.md")
        self.internal_errors: List[str] = []

    def _glob(self, *tail: str) -> List[str]:
        return glob_in(self.memory_dir, *tail)

    def _guard(self, label: str, func: Callable[..., object], *args: object) -> object:
        """Run one check; record an internal error and return None instead of raising."""
        try:
            return func(*args)
        except Exception as exc:  # pylint: disable=broad-exception-caught
            self.internal_errors.append(f"internal error in {label}: {type(exc).__name__}: {exc}")
            return None

    def internal_messages(self) -> List[Message]:
        """Internal errors recorded by _guard, as stderr messages."""
        return [("err", text) for text in self.internal_errors]

    def _project_paths(self) -> List[str]:
        return self._glob("project_*.md")

    def _project_frontmatters(
        self, paths: Optional[Sequence[str]]
    ) -> List[Tuple[str, Dict[str, object]]]:
        """Return (path, frontmatter) for every existing `type: project` file."""
        if paths is None:
            paths = self._project_paths()
        found = []
        for path in sorted(paths):
            if not os.path.isfile(path):
                continue
            fm = parse_frontmatter(path)
            if not fm or fm.get("type") != "project":
                continue
            found.append((path, fm))
        return found

    def find_invalid_statuses(
        self, paths: Optional[Sequence[str]] = None
    ) -> List[Tuple[str, str]]:
        """Collect project files whose `status` is outside VALID_STATUSES.

        Runs independently of the dashboard's observe_until branching, because
        a file with an unknown status but a live observe_until still renders
        and its typo would otherwise never surface.

        Args:
            paths: Files to check. Defaults to every project_*.md.

        Returns:
            (filename, status) pairs, sorted by filename.
        """
        invalid = []
        for path, fm in self._project_frontmatters(paths):
            status = fm.get("status")
            if status is not None and status not in VALID_STATUSES:
                invalid.append((os.path.basename(path), str(status)))
        return invalid

    def find_malformed_checkpoints(
        self, paths: Optional[Sequence[str]] = None
    ) -> List[Tuple[str, str]]:
        """Collect `checkpoints` items that do not parse as "<ISO date> | <text>".

        A checkpoint whose date is malformed never comes due, so it is a
        validation error rather than something rendered best-effort.

        Args:
            paths: Files to check. Defaults to every project_*.md.

        Returns:
            (filename, raw item) pairs, sorted by filename.
        """
        malformed = []
        for path, fm in self._project_frontmatters(paths):
            for raw in fm.get("checkpoints", []):  # type: ignore[union-attr]
                match = CHECKPOINT_RE.match(raw)
                if not match:
                    malformed.append((os.path.basename(path), raw))
                    continue
                try:
                    date.fromisoformat(match.group(1))
                except ValueError:
                    malformed.append((os.path.basename(path), raw))
        return malformed

    def _scan_list_problems(
        self, paths: Optional[Sequence[str]]
    ) -> Tuple[List[Tuple[str, int, str]], List[Tuple[str, int, str]]]:
        """Scan project frontmatter for list keys that the parser would drop.

        Returns:
            (zero_indent, scalar): unindented `- item` lines under an open
            `checkpoints:`/`chores:` key, and `checkpoints:`/`chores:` lines that
            carry a scalar value instead of a list. Triples are (filename,
            1-based line number, stripped line).
        """
        zero_indent: List[Tuple[str, int, str]] = []
        scalar: List[Tuple[str, int, str]] = []
        for path, _ in self._project_frontmatters(paths):
            fname = os.path.basename(path)
            lines = read_text(path).split("\n")
            list_key: Optional[str] = None
            for number, line in enumerate(lines[1:], start=2):
                if line.strip() == "---":
                    break
                if ZERO_INDENT_ITEM_RE.match(line) and list_key:
                    zero_indent.append((fname, number, line.strip()))
                    continue
                match = KV_RE.match(line)
                if match and not LIST_ITEM_RE.match(line):
                    key, value = match.group(1), match.group(2).strip()
                    kind = list_header_kind(value) if key in LIST_KEYS else "n/a"
                    list_key = key if kind == "open" else None
                    if kind is None:
                        scalar.append((fname, number, line.strip()))
        return zero_indent, scalar

    def find_zero_indent_items(
        self, paths: Optional[Sequence[str]] = None
    ) -> List[Tuple[str, int, str]]:
        """Collect unindented `- item` lines under a `checkpoints:`/`chores:` key.

        The parser only binds indented items to a list key, so an unindented
        item is valid YAML but would be silently dropped from the dashboard.

        Args:
            paths: Files to check. Defaults to every project_*.md.

        Returns:
            (filename, 1-based line number, stripped line) triples.
        """
        return self._scan_list_problems(paths)[0]

    def find_scalar_list_values(
        self, paths: Optional[Sequence[str]] = None
    ) -> List[Tuple[str, int, str]]:
        """Collect `checkpoints:`/`chores:` lines holding a scalar, not a list.

        Such a value is ignored by the parser, so the entry would never come
        due. `[]` and `key:  # comment` are valid empty lists and not reported.

        Args:
            paths: Files to check. Defaults to every project_*.md.

        Returns:
            (filename, 1-based line number, stripped line) triples.
        """
        return self._scan_list_problems(paths)[1]

    def find_untyped_project_files(self) -> List[str]:
        """Collect top-level project_*.md files that lack `type: project`.

        Both the dashboard and every check skip such files, so a missing or
        mistyped `type` makes a project invisible. Whole-directory property:
        only used by the unscoped run.

        Returns:
            Sorted filenames.
        """
        untyped = []
        for path in self._project_paths():
            if not os.path.isfile(path):
                continue
            fm = parse_frontmatter(path)
            if not fm or fm.get("type") != "project":
                untyped.append(os.path.basename(path))
        return sorted(untyped)

    def check_index_coverage(self) -> Tuple[List[str], List[str]]:
        """Cross-check MEMORY.md + archive_index.md against files on disk.

        This is a whole-index property, so it takes no path filter: a scoped
        run would report every unlisted file as missing.

        Returns:
            (unindexed, dangling): memory files no index link reaches, and
            index links pointing at a path that does not exist.
        """
        if not os.path.isfile(self.index_path):
            return [], []

        linked = set()
        for index_path in (self.index_path, self.archive_index_path):
            if os.path.isfile(index_path):
                linked |= set(LINK_RE.findall(read_text(index_path)))

        on_disk = set()
        for path in self._glob("**", "*.md"):
            rel = os.path.relpath(path, self.memory_dir)
            if os.path.basename(rel) in NON_INDEXED_FILES:
                continue
            on_disk.add(rel)

        unindexed = sorted(on_disk - linked)
        dangling = sorted(
            rel for rel in linked if not os.path.isfile(os.path.join(self.memory_dir, rel))
        )
        return unindexed, dangling

    def _wikilink_targets(self) -> set:
        """Every name a `[[link]]` may resolve to, with `-` normalised to `_`.

        Both the filename stem and the frontmatter `name:` field are valid.
        """
        targets = set()
        for path in self._glob("**", "*.md"):
            base = os.path.basename(path)
            if base in NON_INDEXED_FILES:
                continue
            targets.add(base[:-3].replace("-", "_"))
            fm = parse_frontmatter(path) or {}
            name = fm.get("name")
            if name:
                targets.add(str(name).replace("-", "_"))
        return targets

    def find_dangling_wikilinks(
        self, paths: Optional[Sequence[str]] = None
    ) -> List[Tuple[str, str]]:
        """Collect `[[links]]` that resolve to no memory file.

        The target set is always built from every file, but only `paths` are
        scanned for links, which makes this check usable in a write-time hook.

        Args:
            paths: Files whose links to check. Defaults to every .md file.

        Returns:
            Sorted unique (relative filename, link text) pairs.
        """
        if paths is None:
            paths = self._glob("**", "*.md")

        # Read the scanned files first: the (whole-directory) target set is only
        # built when some scanned file actually contains a `[[`.
        scanned = []
        for path in sorted(paths):
            if not os.path.isfile(path) or os.path.basename(path) in NON_INDEXED_FILES:
                continue
            text = read_text(path)
            if "[[" in text:
                scanned.append((path, text))
        if not scanned:
            return []
        targets = self._wikilink_targets()

        dangling = []
        for path, text in scanned:
            for link in WIKILINK_RE.findall(text):
                if not WIKILINK_TARGET_RE.match(link):
                    continue
                key = link.split("/")[-1].replace("-", "_")
                if key not in targets:
                    dangling.append((os.path.relpath(path, self.memory_dir), link))
        return sorted(set(dangling))

    # --- reporting -------------------------------------------------------

    def status_messages(self, invalid: List[Tuple[str, str]]) -> List[Message]:
        """Format invalid status findings."""
        allowed = ", ".join(sorted(VALID_STATUSES))
        msgs: List[Message] = [("err", f"invalid status value(s) found — allowed: {allowed}")]
        msgs += [("err", f"  {fname}: status: {status}") for fname, status in invalid]
        return msgs

    def checkpoint_messages(self, malformed: List[Tuple[str, str]]) -> List[Message]:
        """Format malformed checkpoint findings."""
        hint = self.strings["cp_hint"]
        msgs: List[Message] = [
            ("err", f'malformed checkpoint(s) — each item must be "YYYY-MM-DD | {hint}":')
        ]
        msgs += [("err", f"  {fname}: - {raw}") for fname, raw in malformed]
        return msgs

    def zero_indent_messages(self, items: List[Tuple[str, int, str]]) -> List[Message]:
        """Format zero-indent list item findings."""
        msgs: List[Message] = [("err", self.strings["zero_indent"])]
        msgs += [("err", f"  {fname}:{number}: {raw}") for fname, number, raw in items]
        return msgs

    def scalar_list_messages(self, items: List[Tuple[str, int, str]]) -> List[Message]:
        """Format scalar-on-list-key findings."""
        msgs: List[Message] = [("err", self.strings["scalar_list"])]
        msgs += [("err", f"  {fname}:{number}: {raw}") for fname, number, raw in items]
        return msgs

    def untyped_messages(self, names: List[str]) -> List[Message]:
        """Format findings for project_*.md files without `type: project`."""
        msgs: List[Message] = [("err", self.strings["not_project"])]
        msgs += [("err", f"  {name}") for name in names]
        return msgs

    def wikilink_messages(self, dangling: List[Tuple[str, str]]) -> List[Message]:
        """Format dangling wikilink findings."""
        msgs: List[Message] = [
            (
                "err",
                "[[wikilink]](s) pointing at no memory file — check for a renamed, "
                "deleted or misspelled target:",
            )
        ]
        msgs += [("err", f"  {rel}: [[{link}]]") for rel, link in dangling]
        return msgs

    def index_messages(self, unindexed: List[str], dangling: List[str]) -> List[Message]:
        """Format index coverage findings."""
        msgs: List[Message] = []
        if unindexed:
            msgs.append(
                (
                    "err",
                    "memory file(s) not reachable from MEMORY.md or archive_index.md — "
                    "active projects need an index line, closed ones need an "
                    "archive_index.md link, or they become undiscoverable:",
                )
            )
            msgs += [("err", f"  {rel}") for rel in unindexed]
        if dangling:
            msgs.append(("err", "MEMORY.md link(s) pointing at a missing file:"))
            msgs += [("err", f"  {rel}") for rel in dangling]
        return msgs

    def warnings(self) -> List[Message]:
        """Findings printed after a normal regenerate (reported, not fatal)."""
        msgs: List[Message] = []
        invalid = self._guard("status check", self.find_invalid_statuses)
        if invalid:
            msgs += self.status_messages(invalid)  # type: ignore[arg-type]
        malformed = self._guard("checkpoint check", self.find_malformed_checkpoints)
        if malformed:
            msgs += self.checkpoint_messages(malformed)  # type: ignore[arg-type]
        flat = self._guard("list indentation check", self.find_zero_indent_items)
        if flat:
            msgs += self.zero_indent_messages(flat)  # type: ignore[arg-type]
        scalars = self._guard("list value check", self.find_scalar_list_values)
        if scalars:
            msgs += self.scalar_list_messages(scalars)  # type: ignore[arg-type]
        untyped = self._guard("project type check", self.find_untyped_project_files)
        if untyped:
            msgs += self.untyped_messages(untyped)  # type: ignore[arg-type]
        bad_links = self._guard("wikilink check", self.find_dangling_wikilinks)
        if bad_links:
            msgs += self.wikilink_messages(bad_links)  # type: ignore[arg-type]
        coverage = self._guard("index check", self.check_index_coverage)
        if coverage:
            msgs += self.index_messages(*coverage)  # type: ignore[misc]
        return msgs + self.internal_messages()

    def validate(self, paths: Optional[Sequence[str]] = None) -> Tuple[int, List[Message]]:
        """Run every check; one crashing check never hides the others' findings.

        Args:
            paths: Files to check. When set, the index coverage check is
                skipped because a scoped run has no opinion on the whole index.

        Returns:
            (exit code, messages): 1 if any check reported a finding, else 0.
            Internal errors are recorded in `self.internal_errors`, not in the
            exit code, so callers decide how to treat them.
        """
        failed = False
        msgs: List[Message] = []

        invalid = self._guard("status check", self.find_invalid_statuses, paths)
        if invalid:
            msgs += self.status_messages(invalid)  # type: ignore[arg-type]
            failed = True
        elif invalid is not None:
            msgs.append(("out", "all project_*.md status values valid"))

        malformed = self._guard("checkpoint check", self.find_malformed_checkpoints, paths)
        if malformed:
            msgs += self.checkpoint_messages(malformed)  # type: ignore[arg-type]
            failed = True
        elif malformed is not None:
            msgs.append(("out", "all checkpoints parse"))

        # No OK line for this check: a clean run keeps the historical output.
        flat = self._guard("list indentation check", self.find_zero_indent_items, paths)
        if flat:
            msgs += self.zero_indent_messages(flat)  # type: ignore[arg-type]
            failed = True

        scalars = self._guard("list value check", self.find_scalar_list_values, paths)
        if scalars:
            msgs += self.scalar_list_messages(scalars)  # type: ignore[arg-type]
            failed = True

        if paths is None:
            untyped = self._guard("project type check", self.find_untyped_project_files)
            if untyped:
                msgs += self.untyped_messages(untyped)  # type: ignore[arg-type]
                failed = True

        bad_links = self._guard("wikilink check", self.find_dangling_wikilinks, paths)
        if bad_links:
            msgs += self.wikilink_messages(bad_links)  # type: ignore[arg-type]
            failed = True
        elif bad_links is not None:
            msgs.append(("out", "all wikilinks resolve"))

        if paths is None:
            coverage = self._guard("index check", self.check_index_coverage)
            if coverage is not None:
                unindexed, dangling = coverage  # type: ignore[misc]
                if unindexed or dangling:
                    msgs += self.index_messages(unindexed, dangling)
                    failed = True
                else:
                    msgs.append(
                        (
                            "out",
                            "all memory files reachable from MEMORY.md/archive_index.md, "
                            "no dangling links",
                        )
                    )
        return (1 if failed else 0), msgs


@dataclass
class DashboardResult:
    """Rendered dashboard text plus per-section counts."""

    text: str
    counts: Dict[str, int] = field(default_factory=dict)


class DashboardBuilder:
    """Render dashboard.md from the project frontmatter of a memory directory."""

    def __init__(self, memory_dir: str, strings: Dict[str, str], today: date) -> None:
        """Bind the builder to a directory, a locale table and a date."""
        self.memory_dir = memory_dir
        self.strings = strings
        self.today = today

    def _line(
        self,
        fm: Dict[str, object],
        fname: str,
        observe_until: Optional[str] = None,
        overdue_days: Optional[int] = None,
    ) -> str:
        title = fm.get("name", fname)
        desc = fm.get("description", "")
        line = f"- [{title}]({fname})"
        if observe_until:
            line += self.strings["observe_until"].format(observe_until=observe_until)
            if overdue_days is not None:
                line += format_overdue(self.strings, overdue_days)
        line += f" — {desc}"
        return line

    def build(self) -> DashboardResult:
        """Collect every project and render the sections.

        Returns:
            The dashboard text and a dict of section counts.
        """
        s = self.strings
        overdue: List[Tuple[str, str]] = []
        observing: List[Tuple[str, str]] = []
        active: List[Tuple[str, str]] = []
        todo: List[Tuple[str, str]] = []
        checkpoints: List[Tuple[str, str]] = []
        chores: List[Tuple[str, str]] = []

        for path in sorted(glob_in(self.memory_dir, "project_*.md")):
            fm = parse_frontmatter(path)
            if not fm or fm.get("type") != "project":
                continue
            status = fm.get("status")
            if status is None:
                continue
            fname = os.path.basename(path)

            # Chores outlive their project on purpose: the moment a project goes
            # terminal it leaves every other section, and its leftovers are then
            # the ones most likely to be forgotten.
            for raw in fm.get("chores", []):  # type: ignore[union-attr]
                # No checkbox: dashboard.md is generated, so a tickable-looking box
                # would imply an affordance that regeneration silently discards.
                chores.append((fname, f"- {raw} — [{fname}]({fname})"))

            # Terminal states are skipped before the observe_until branch so a
            # stale deadline on a finished project cannot resurrect it.
            if status in TERMINAL_STATUSES:
                continue

            for raw in fm.get("checkpoints", []):  # type: ignore[union-attr]
                match = CHECKPOINT_RE.match(raw)
                if not match:
                    continue  # reported by validate; never silently rendered wrong
                cp_date, what = match.group(1), match.group(2)
                try:
                    due = date.fromisoformat(cp_date)
                except ValueError:
                    continue
                line = f"- {cp_date} — {what} — [{fname}]({fname})"
                if due < self.today:
                    line += format_overdue(s, (self.today - due).days)
                elif due == self.today:
                    line += s["due_today"]
                checkpoints.append((cp_date, line))

            observe_until = fm.get("observe_until")

            # observe_until is checked regardless of status: a file left at
            # "active" while carrying a deadline must still warn when it lapses.
            if observe_until:
                try:
                    deadline: Optional[date] = date.fromisoformat(str(observe_until))
                except ValueError:
                    deadline = None
                if deadline and deadline < self.today:
                    days = (self.today - deadline).days
                    overdue.append(
                        (str(observe_until), self._line(fm, fname, str(observe_until), days))
                    )
                    continue
                observing.append((str(observe_until), self._line(fm, fname, str(observe_until))))
            elif status == "observing":
                observing.append(("9999-99-99", self._line(fm, fname)))
            elif status == "active":
                active.append((fname, self._line(fm, fname)))
            elif status == "todo":
                todo.append((fname, self._line(fm, fname)))

        sections = [
            ("sec_overdue", overdue),
            ("sec_checkpoints", checkpoints),
            ("sec_chores", chores),
            ("sec_observing", observing),
            ("sec_active", active),
            ("sec_todo", todo),
        ]
        for _, items in sections:
            items.sort()

        generated = s["generated"].format(date=self.today.isoformat())
        out = [s["title"] + "\n", s["banner"] + "\n", generated + "\n"]
        for index, (key, items) in enumerate(sections):
            out.append(("\n" if index == 0 else "\n\n") + s[key] + "\n")
            if items:
                out.extend(line for _, line in items)
            else:
                out.append(s["empty"])
        out.append("")

        counts = {
            "overdue": len(overdue),
            "observing": len(observing),
            "active": len(active),
            "todo": len(todo),
            "checkpoints": len(checkpoints),
            "chores": len(chores),
        }
        return DashboardResult(text="\n".join(out) + "\n", counts=counts)


def emit(messages: Sequence[Message]) -> None:
    """Print messages to their streams (user-facing CLI output)."""
    for stream, text in messages:
        print(text, file=sys.stderr if stream == "err" else sys.stdout)


def resolve_locale(name: Optional[str]) -> Dict[str, str]:
    """Pick a locale table from a flag value or the environment."""
    chosen = name or os.environ.get(ENV_LOCALE) or DEFAULT_LOCALE
    if chosen not in LOCALES:
        raise LedgerError(f"unknown locale {chosen!r}; available: {', '.join(sorted(LOCALES))}")
    return LOCALES[chosen]


def resolve_memory_dir(flag: Optional[str]) -> str:
    """Pick the memory directory from the flag or the environment; never guess."""
    chosen = flag or os.environ.get(ENV_DIR)
    if not chosen:
        raise LedgerError(f"no memory directory: pass --memory-dir or set {ENV_DIR}")
    if not os.path.isdir(chosen):
        raise LedgerError(f"memory directory does not exist: {chosen}")
    return os.path.abspath(chosen)


def cmd_generate(args: argparse.Namespace) -> int:
    """Write dashboard.md (or --output) and print the summary plus warnings."""
    memory_dir = resolve_memory_dir(args.memory_dir)
    strings = resolve_locale(args.locale)
    try:
        today = date.fromisoformat(args.today) if args.today else date.today()
    except ValueError as exc:
        raise LedgerError(f"invalid --today value: {exc}") from exc
    result = DashboardBuilder(memory_dir, strings, today).build()
    output = args.output or os.path.join(memory_dir, "dashboard.md")
    try:
        with open(output, "w", encoding="utf-8") as handle:
            handle.write(result.text)
    except OSError as exc:
        raise LedgerError(f"cannot write {output}: {exc}") from exc
    c = result.counts
    print(
        f"wrote {output}: {c['overdue']} overdue, {c['observing']} observing, "
        f"{c['active']} active, {c['todo']} todo, {c['checkpoints']} checkpoints, "
        f"{c['chores']} chores"
    )
    emit(Validator(memory_dir, strings).warnings())
    return 0


def cmd_validate(args: argparse.Namespace) -> int:
    """Validate the memory directory; exit 1 on findings, 2 on usage or internal errors."""
    memory_dir = resolve_memory_dir(args.memory_dir)
    strings = resolve_locale(args.locale)
    for name in args.files:
        if not os.path.isfile(name):
            raise LedgerError(f"file does not exist: {name}")
    validator = Validator(memory_dir, strings)
    code, msgs = validator.validate(args.files or None)
    emit(msgs)
    if validator.internal_errors:
        emit(validator.internal_messages())
        code = code or 2
    return code


def hook_target(payload: object) -> Optional[str]:
    """Return the edited memory file path, or None when the hook should no-op."""
    if not isinstance(payload, dict):
        return None
    tool_input = payload.get("tool_input")
    if not isinstance(tool_input, dict):
        return None
    file_path = tool_input.get("file_path")
    if not isinstance(file_path, str) or not file_path:
        return None
    parent = os.path.basename(os.path.dirname(file_path))
    if parent != HOOK_DIR_NAME or not fnmatch.fnmatch(os.path.basename(file_path), HOOK_FILE_GLOB):
        return None
    return file_path if os.path.isfile(file_path) else None


def cmd_hook(_args: argparse.Namespace) -> int:
    """PostToolUse hook: scoped validate of one edited memory project file.

    Silent exit 0 for anything that is not an existing `*/memory/project_*.md`
    file with `type: project` frontmatter, for unreadable input, and for
    internal errors (fail open). Exit 2 with the findings on stderr otherwise;
    findings already collected are never dropped by a later internal error.
    """
    try:
        raw = sys.stdin.buffer.read().decode("utf-8", errors="replace")
        target = hook_target(json.loads(raw))
        if target is None:
            return 0
        fm = parse_frontmatter(target)
        if not fm or fm.get("type") != "project":
            return 0
        try:
            strings = resolve_locale(None)
        except LedgerError:
            strings = LOCALES[DEFAULT_LOCALE]
        memory_dir = os.path.dirname(os.path.abspath(target))
        validator = Validator(memory_dir, strings)
        code, msgs = validator.validate([target])
        if code == 0:
            return 0
        findings = [text for stream, text in msgs if stream == "err"]
        findings += [text for _, text in validator.internal_messages()]
        for text in findings + [strings["hook_hint"]]:
            print(text, file=sys.stderr)
        return 2
    except Exception:  # pylint: disable=broad-exception-caught
        return 0


def build_parser() -> argparse.ArgumentParser:
    """Build the argument parser for all subcommands."""
    parser = argparse.ArgumentParser(prog="memory-ledger", description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="command", required=True)

    gen = sub.add_parser("generate", help="regenerate dashboard.md")
    gen.add_argument("--memory-dir", help=f"memory directory (env: {ENV_DIR})")
    gen.add_argument("--output", help="output path (default: <memory-dir>/dashboard.md)")
    gen.add_argument("--locale", help=f"en or zh-TW (env: {ENV_LOCALE}, default en)")
    gen.add_argument("--today", help="override today's date, YYYY-MM-DD (for tests)")
    gen.set_defaults(func=cmd_generate)

    val = sub.add_parser("validate", help="check statuses, checkpoints, links and indexes")
    val.add_argument("--memory-dir", help=f"memory directory (env: {ENV_DIR})")
    val.add_argument("--locale", help=f"en or zh-TW (env: {ENV_LOCALE}, default en)")
    val.add_argument("files", nargs="*", help="limit the check to these files (skips index check)")
    val.set_defaults(func=cmd_validate)

    hook = sub.add_parser("hook", help="PostToolUse hook; reads JSON on stdin")
    hook.set_defaults(func=cmd_hook)
    return parser


def main(argv: Optional[Sequence[str]] = None) -> int:
    """CLI entry point."""
    args = build_parser().parse_args(argv)
    try:
        return args.func(args)
    except LedgerError as exc:
        print(f"memory-ledger: {exc}", file=sys.stderr)
        return 2
    except Exception as exc:  # pylint: disable=broad-exception-caught
        print(f"memory-ledger: internal error: {type(exc).__name__}: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
