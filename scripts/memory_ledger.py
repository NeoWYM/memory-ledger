KV_RE = re.compile(r"^\s*([a-zA-Z_]+):\s*(.*)$")

# A list item inside a frontmatter block: "    - <text>".
LIST_ITEM_RE = re.compile(r"^\s+-\s+(.*)$")

# Frontmatter keys parsed as lists rather than scalars. Any other key keeps the
# flat key/value treatment, including `metadata:` whose indented children are
# deliberately flattened into the top level (that is how `status` is read).
LIST_KEYS = {"checkpoints", "chores"}

# "2026-08-14 | verify the first scheduled run". The date is what makes a
# checkpoint come due, so it is required and validated, not free text.
CHECKPOINT_RE = re.compile(r"^(\d{4}-\d{2}-\d{2})\s*\|\s*(\S.*)$")

# Terminal states leave the dashboard; "superseded" is kept distinct from
# "done" because "replaced by another file" is a different fact.
TERMINAL_STATUSES = {"done", "superseded"}

# Any other value would silently drop a project off the dashboard.
VALID_STATUSES = TERMINAL_STATUSES | {"observing", "active", "todo"}

# Generated or index files: they are the map, not the territory.
NON_INDEXED_FILES = {"MEMORY.md", "dashboard.md", "archive_index.md"}

# An unindented list item, which the parser would silently drop.
ZERO_INDENT_ITEM_RE = re.compile(r"^-\s+\S")

DOUBLE_ESCAPE_RE = re.compile(r'\\(["\\])')
COMMENT_RE = re.compile(r"(^|\s)#.*$")
EMPTY_FLOW_LIST_RE = re.compile(r"^\[\s*\]$")

LINK_RE = re.compile(r"\(([\w\-/]+\.md)\)")
WIKILINK_RE = re.compile(r"\[\[([^\[\]]+)\]\]")

# Anything else inside [[ ]] (e.g. JSON like [["a","b"]]) is not a link at all.
WIKILINK_TARGET_RE = re.compile(r"^[\w\-/]+$")

